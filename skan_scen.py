#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
skan_scen — находит принципиально разные кадры в папке ekran.

3122 снимка глазами не прочитать: почти все они повторяют один и тот
же экран. Поэтому сначала делим кадры на сцены по похожести, а потом
разбираем только представителей сцен — это в разы меньше работы.

Как делим: сжимаем кадр до 32×32 в градациях серого, сравниваем
не с предыдущим кадром, а с ЯКОРЯ сцены. Иначе мелкий шум (курсор,
счётчик секунд) накапливается и сцену режет на куски.

Кадры сгруппированы по времени съёмки: между 12:19 и 13:22 был
перерыв, такие разрывы всегда дают новую сцену.
"""
from __future__ import annotations

import sys
from pathlib import Path

from PIL import Image

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

# Папка с кадрами. Раньше здесь был жёстко прописан путь к рабочей
# папке на одной конкретной машине, и на любом другом компьютере
# скрипт просто не находил ничего, тихо выдавая пустой результат.
# Теперь путь можно задать ключом, а по умолчанию берётся папка
# рядом со скриптом.
ПАПКА = Path(sys.argv[1]) if len(sys.argv) > 1 else \
    Path(__file__).resolve().parent / "snimki"
РАЗМЕР = 32
ЧУТСТВИТЕЛЬНОСТЬ = 10
ПОРОГ_НОВОЙ_СЦЕНЫ = 0.14
РАЗРЫВ_МИНУТ = 4


def метка(путь: Path) -> list[int]:
    """Отпечаток кадра: маленькая серая картинка списком пикселей."""
    with Image.open(путь) as im:
        im = im.convert("L")
        im.thumbnail((РАЗМЕР, РАЗМЕР))
        данные = list(im.getdata())
    return данные


def разница(a: list[int], b: list[int]) -> float:
    if not a or len(a) != len(b):
        return 1.0
    разные = sum(1 for x, y in zip(a, b) if abs(x - y) > ЧУТСТВИТЕЛЬНОСТЬ)
    return разные / len(a)


def кадры() -> list[Path]:
    # Расширение спросим у папки: съёмка пишет и .png, и .jpg,
    # и поиск только по .png просто перестал бы видеть кадры.
    файлы = [p for расширение in ("*.png", "*.jpg")
             for p in ПАПКА.glob(расширение) if p.is_file()]
    файлы.sort(key=lambda p: (p.stat().st_mtime, p.name))
    return файлы


def найти_сцены(файлы: list[Path]) -> list[dict]:
    """Делит кадры на сцены, возвращает список сцен."""
    сцены: list[dict] = []
    текущая: dict | None = None
    якорь: list[int] | None = None
    прошлый_время = None

    for i, файл in enumerate(файлы, 1):
        время = файл.stat().st_mtime
        try:
            м = метка(файл)
        except Exception:                                            # noqa: BLE001
            continue

        новый = False
        if текущая is None:
            новый = True
        else:
            # большой перерыв во времени — всегда новая сцена
            if прошлый_время and (время - прошлый_время) > РАЗРЫВ_МИНУТ * 60:
                новый = True
            elif разница(якорь, м) > ПОРОГ_НОВОЙ_СЦЕНЫ:
                новый = True

        if новый:
            текущая = {
                "первый": файл, "первый_время": время,
                "последний": файл, "последний_время": время,
                "кадров": 1, "метка": м,
            }
            сцены.append(текущая)
            якорь = м
        else:
            текущая["последний"] = файл
            текущая["последний_время"] = время
            текущая["кадров"] += 1

        прошлый_время = время
        if i % 400 == 0:
            print(f"  разобрано {i}/{len(файлы)}, сцен пока {len(сцены)}",
                  flush=True)

    return сцены


def время_текстом(t: float) -> str:
    from datetime import datetime
    return datetime.fromtimestamp(t).strftime("%d.%m %H:%M:%S")


def главная() -> int:
    файлы = кадры()
    print(f"кадров: {len(файлы)}")
    print("ищу сцены...\n")

    сцены = найти_сцены(файлы)

    print("\n" + "=" * 72)
    print(f"  СЦЕН: {len(сцены)}  (средняя длина "
          f"{len(файлы) / max(1, len(сцены)):.0f} кадра на сцену)")
    print("=" * 72)

    долгие = sorted(сцены, key=lambda s: -s["кадров"])
    print("\nСамые долгие сцены (по сколько кадров в них снимали):")
    for s in долгие[:15]:
        print(f"  {время_текстом(s['первый_время'])} — "
              f"{время_текстом(s['последний_время'])}  "
              f"{s['кадров']:>5} кадров  ({время_текстом(s['первый_время'])} …)")
        print(f"      {s['последний'].name}")

    out = ПАПКА.parent / "tools" / "sceny.json"
    import json
    данные = [
        {
            "первый": str(s["первый"]),
            "последний": str(s["последний"]),
            "первый_время": s["первый_время"],
            "последний_время": s["последний_время"],
            "кадров": s["кадров"],
        }
        for s in сцены
    ]
    out.write_text(json.dumps(данные, ensure_ascii=False, indent=1),
                   encoding="utf-8")
    print(f"\nСписок сцен сохранён: {out}")
    return 0


if __name__ == "__main__":
    sys.exit(главная())
