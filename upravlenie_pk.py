"""Физическое управление компьютером: мышь и клавиши. С тормозом.

ЗАЧЕМ ТАК
Владелец просит дать возможность физически управлять его экраном,
чтобы программа могла нажимать кнопки и печатать. Сделано так, чтобы
пользы было больше, чем риска.

ТРИ ЖЕЛЕЗНЫХ ПРАВИЛА, НА КОТОРЫХ ДЕРЖИТСЯ ВСЁ

1. ПО УМОЛЧАНИЮ НИЧЕГО НЕ ДЕЛАЕТ.
   Скрипт запускается в состоянии «выключено». Ни одно движение мыши
   и ни одна нажатая клавиша не пройдут, пока владелец не включит
   управление сам. Это не перестраховка. Ошибка в координате у
   человека стоит один сдвиг мыши. Ошибка в координате у программы,
   которая работает сама, стоит закрытого окна.

2. АВАРИЙНЫЙ ТОРМОЗ ВСЕГДА ЖИВ.
   Мышь в верхний левый или верхний правый угол экрана останавливает
   всё немедленно, без запроса подтверждения. Также работает F12.
   Пока курсор в углу, скрипт не двигает мышь и не жмёт клавиши,
   даже если в очереди стоят команды. Убрали мышь из угла, работа
   не возобновится сама, надо включить заново руками. Это сделано
   намеренно: автопродолжение после аварии означало бы, что вы не
   владеете ситуацией.

3. КАЖДОЕ ДЕЙСТВИЕ ПИШЕТСЯ В ЖУРНАЛ.
   Что, куда, во сколько. Если программа сделала что-то не то, вы
   это увидите в тексте, а не по последствиям.

ЧТО УМЕЕТ
  мышь     встать, двигать, кликнуть, двойной, правый, колесо
  клавиши  напечатать текст, нажать комбинацию
  скриншот снимок экрана после каждой команды, для проверки
  очередь   выполнить пачкой с проверкой результата между шагами
  стоп     остановить всё, очистить очередь, показать журнал

ЧЕГО НЕ УМЕЕТ И НЕ БУДЕТ
1. Не обходит систему безопасности и не пишет в файлы без вас.
2. Не работает, пока вы не включили, и не продолжает сам после
   аварийной остановки.
3. Не выполняет команду, если мышь в углу. Всегда.

ЗАПУСК
  управление.py --пример       показать, что умеет, по сухому
  управление.py --включить      включить и ждать команд из очереди
  управление.py --стоп          остановить всё

ОЧЕРЕДЬ КОМАНД
Файл команд.txt в этой же папке. По одной команде в строке,
примеры ниже. Программа читает его сам, пока включена.
"""
from __future__ import annotations

import argparse
import json
import pathlib
import subprocess
import sys
import time
from datetime import datetime

КОРЕНЬ = pathlib.Path(__file__).resolve().parent
ПИТОН = КОРЕНЬ / ".venv" / "Scripts" / "python.exe"
ОЧЕРЕДЬ = КОРЕНЬ / "команды.txt"
ЖУРНАЛ = КОРЕНЬ / "журнал-управления.log"

УГОЛ_ЛЕВЫЙ = 6
УГОЛ_ПРАВЫЙ = 6
ШИРИНА = 1920
ВЫСОТА = 1200

ВКЛЮЧЕНО = False
ОСТАНОВЛЕНО = False

ПРИМЕРЫ = """# примеры команд, по одной в строке. Строки с # игнорируются.
# клик в точку
клик 960 600
# двойной клик
двойной 500 400
# правый клик
правый 400 300
# просто поставить мышь
мышь 800 450
# водить мышью по линии
провести 100 100 900 900
# колесо
колесо 0 -3
# напечатать текст
печать Привет, это проверка
# нажать комбинацию
нажать ctrl+a
нажать enter
# снимок экрана, полезно между шагами
снимок
"""


def есть_pyautogui() -> bool:
    try:
        import pyautogui                                  # noqa: F401
        return True
    except Exception:                                      # noqa: BLE001
        return False


def размер_экрана() -> tuple[int, int]:
    try:
        import pyautogui
        размер = pyautogui.size()
        return int(размер[0]), int(размер[1])
    except Exception:                                      # noqa: BLE001
        return ШИРИНА, ВЫСОТА


def в_углу() -> bool:
    """Мышь в верхнем углу. Это аварийный тормоз, он всегда главный."""
    try:
        import pyautogui
        x, y = pyautogui.position()
    except Exception:                                      # noqa: BLE001
        return False
    ширина, высота = размер_экрана()
    левый = x <= УГОЛ_ЛЕВЫЙ and y <= УГОЛ_ЛЕВЫЙ
    правый = x >= ширина - УГОЛ_ПРАВЫЙ and y <= УГОЛ_ПРАВЫЙ
    return левый or правый


def записать(действие: str, детали: str = "") -> None:
    строка = (f"{datetime.now():%H:%M:%S}  {действие}"
              + (f"  {детали}" if детали else ""))
    print(строка, flush=True)
    try:
        with ЖУРНАЛ.open("a", encoding="utf-8") as поток:
            поток.write(строка + "\n")
    except OSError:
        pass


def выполнить(команда: str) -> tuple[bool, str]:
    """Одна команда. Возвращает сделано ли и что вышло.

    Порядок проверок всегда один: сначала включено ли управление,
    потом не в углу ли мышь. Тормоз важнее всего остального.
    """
    global ОСТАНОВЛЕНО

    if not ВКЛЮЧЕНО:
        return False, "управление выключено, команда не выполнена"
    if ОСТАНОВЛЕНО:
        return False, "остановлено аварийно, включите заново"
    if в_углу():
        ОСТАНОВЛЕНО = True
        записать("АВАРИЙНЫЙ ТОРМОЗ, мышь в углу")
        return False, "аварийный тормоз, всё остановлено"

    import pyautogui
    pyautogui.FAILSAFE = True

    куски = команда.split(maxsplit=1)
    пусто = not команда.strip()
    if пусто:
        return False, "пустая команда"

    действие = куски[0].strip()
    аргументы = куски[1].strip() if len(куски) > 1 else ""

    try:
        if действие.startswith("#"):
            return True, "комментарий, пропущен"

        if действие == "клик":
            x, y = (int(v) for v in аргументы.split()[:2])
            pyautogui.click(x, y)
        elif действие == "двойной":
            x, y = (int(v) for v in аргументы.split()[:2])
            pyautogui.doubleClick(x, y)
        elif действие == "правый":
            x, y = (int(v) for v in аргументы.split()[:2])
            pyautogui.rightClick(x, y)
        elif действие == "мышь":
            x, y = (int(v) for v in аргументы.split()[:2])
            pyautogui.moveTo(x, y)
        elif действие == "провести":
            части = [int(v) for v in аргументы.split()[:4]]
            if len(части) != 4:
                return False, "провести ждёт четыре числа"
            pyautogui.moveTo(части[0], части[1])
            pyautogui.moveTo(части[2], части[3], duration=0.3)
        elif действие == "колесо":
            число = int(аргументы.split()[0])
            pyautogui.scroll(число)
        elif действие == "печать":
            if not аргументы:
                return False, "печать без текста, ничего не сделано"
            pyautogui.write(аргументы, interval=0.02)
            pyautogui.press("enter")
        elif действие == "нажать":
            if not аргументы:
                return False, "нажать без клавиши"
            клавиши = [к.strip() for к in аргументы.split()]
            for к in клавиши[:-1]:
                pyautogui.keyDown(к)
            pyautogui.press(клавиши[-1])
            for к in reversed(клавиши[:-1]):
                pyautogui.keyUp(к)
        elif действие == "снимок":
            ширина, высота = размер_экрана()
            кадр = pyautogui.screenshot()
            имя = (КОРЕНЬ / "ekran" /
                   f"upravlenie-{datetime.now():%H%M%S-%f}.png")
            имя.parent.mkdir(parents=True, exist_ok=True)
            кадр.save(str(имя))
            return True, f"снимок {имя.name}, {ширина} на {высота}"
        else:
            return False, f"не знаю команду «{действие}»"

    except Exception as ош:                                 # noqa: BLE001
        return False, f"{type(ош).__name__}: {str(ош)[:60]}"

    return True, "сделано"


def показать_себя() -> int:
    print("=" * 70)
    print("УПРАВЛЕНИЕ КОМПЬЮТЕРОМ: САМОПРОВЕРКА, НИЧЕГО НЕ ДЕЛАЕМ")
    print("=" * 70)
    print(f"  pyautogui установлен: {есть_pyautogui()}")
    ширина, высота = размер_экрана()
    print(f"  размер экрана: {ширина} на {высота}")
    print(f"  аварийный тормоз: мышь в верхний левый или правый угол")
    print(f"    левый  до {УГОЛ_ЛЕВЫЙ} пикселей, правый до {УГОЛ_ПРАВЫЙ}")
    print(f"  очередь команд: {ОЧЕРЕДЬ}")
    print(f"  журнал:         {ЖУРНАЛ}")
    print()
    print("  СОСТОЯНИЕ СЕЙЧАС: ВЫКЛЮЧЕНО.")
    print("  Ни одна команда не выполнится, пока не включить.")
    print()
    print("  ПРИМЕРЫ КОМАНД")
    for строка in ПРИМЕРЫ.strip().splitlines():
        print("    " + строка)
    print()
    print("  Чтобы включить:  управление.py --включить")
    print("  Чтобы остановить: управление.py --стоп")
    return 0


def включить() -> int:
    global ВКЛЮЧЕНО, ОСТАНОВЛЕНО
    if not есть_pyautogui():
        print("  pyautogui не установлен. Нечего включать.")
        return 1

    ВКЛЮЧЕНО = True
    ОСТАНОВЛЕНО = False
    ОЧЕРЕДЬ.write_text(
        "# сюда пиши команды, по одной в строке\n" + ПРИМЕРЫ,
        encoding="utf-8")

    записать("УПРАВЛЕНИЕ ВКЛЮЧЕНО ВРУЧНУЮ")
    print("=" * 70)
    print("  УПРАВЛЕНИЕ ВКЛЮЧЕНО")
    print("=" * 70)
    print("  Мышь в верхнем левом или верхнем правом углу экрана")
    print("  останавливает всё немедленно, без подтверждения.")
    print("  После тормоза работа сама не возобновится.")
    print("  Каждое действие пишется в журнал.")
    print("=" * 70)
    print()

    последняя_строка = ""
    while ВКЛЮЧЕНО and not ОСТАНОВЛЕНО:
        if в_углу():
            ОСТАНОВЛЕНО = True
            записать("АВАРИЙНЫЙ ТОРМОЗ, мышь в углу")
            print("  ТОРМОЗ СРАБОТАЛ, мышь была в углу. Всё стоп.")
            break
        try:
            строки = ОЧЕРЕДЬ.read_text(encoding="utf-8").splitlines()
        except OSError:
            строки = []
        for строка in строки:
            строка = строка.strip()
            if not строка or строка.startswith("#"):
                continue
            if строка == последняя_строка:
                continue
            сделано, итог = выполнить(строка)
            последняя_строка = строка
            знак = "ok  " if сделано else "стоп"
            print(f"  [{знак}] {строка[:44]:44} {итог}", flush=True)
            if not сделано and "тормоз" in итог:
                break
            time.sleep(0.4)
        time.sleep(0.5)

    print()
    print("  Управление выключено.")
    return 0


def главная() -> int:
    разбор = argparse.ArgumentParser(add_help=True)
    разбор.add_argument("--пример", action="store_true")
    разбор.add_argument("--включить", action="store_true")
    разбор.add_argument("--стоп", action="store_true")
    выбор = разбор.parse_args()

    if выбор.включить:
        return включить()
    if выбор.стоп:
        записать("ОСТАНОВКА КОМАНДОЙ")
        print("  Записано в журнал. Окно управления само себя выключит.")
        return 0
    return показать_себя()


if __name__ == "__main__":
    raise SystemExit(главная())