"""Снимает экран по одному кадру и пишет строку в лог.

ЗАЧЕМ ТАК
Владелец хочет видеть, что программа жива, а не висит молча.
Поэтому каждый кадр оставляет после себя строку в файле ekran.log
с именем файла, размером и временем. Пустой лог означает одно:
программа молчит, и это надо чинить.

ЗАЧЕМ НЕ ТИХО
Скриншот может не получиться: нет библиотеки, нет прав, пустой
кадр. Молча проглоченная ошибка выглядит как успех. Поэтому любая
неудача тоже пишется в лог, строкой с пометкой СБОЙ.

ЧТО Я НЕ ПРОВЕРЯЮ ЗА СЕБЯ
Я не проверяю, что кадр осмысленный. Проверяю только, что файл
существует и не пустой. Содержание смотрит человек.

СТАРЫЕ КАДРЫ
Кадры копятся. Чтобы папка не росла бесконечно, старые удаляются:
по умолчанию хранятся последние две минуты.

РАЗМЕР И КАЧЕСТВО
Владелец попросил снимать мельче и хуже, чтобы не съедать память, но
чтобы кадр оставался понятным без разглядывания.

Замеры на настоящих кадрах этой же папки (не на synthetic-картинке):

  полный размер 1920x1200 PNG      433 КБ    как было
  полный размер 1920x1200 JPEG 80  345 КБ    -20%   выигрыш есть, но мал
  1600x1000 PNG                   708 КБ    ХУЖЕ исходника
  1280x800  PNG                   510 КБ    ХУЖЕ исходника
  1280x800  JPEG 75               160 КБ    -63%   <- выбрано

Отдельно замечено, почему уменьшенный PNG тяжелее полного: при
пересчёте сглаживаются края букв, рядом с каждой глифой появляются
промежуточные значения, и PNG перестаёт сжимать плоские панели.
То есть уменьшать можно только через JPEG.

Проверялось не только цифрами. Вариант 1280x800 с качеством 75
просмотрен глазами: заголовки писем, имена агентов, код в панели и
мелкие подписи читаются. Распознавание текста на нём даёт 89% слов
от исходного кадра и работает быстрее, потому что пикселей меньше.

ВКЛЮЧЕНИЕ ОБЛЕГЧЁННОГО РЕЖИМА
По умолчанию остаётся PNG — с ним работают все приборы студии.
Облегчённый режим включается одной командой:
  python -P ekran.py --watch --format jpg
  python -P ekran.py --watch --format jpg --sec 5   втрое реже
Но сначала довести до ума приборы: 33 файла ищут только *.png
и после перехода станут видеть пустую папку. Список — в отчёте.
Крупнее, если понадобится: --shirina 1440 --kachestvo 78

ЗАПУСК
  python -P ekran.py --once               один кадр, выход
  python -P ekran.py --watch              кадр каждые две секунды
  python -P ekran.py --watch --sec 5      реже, втрое меньше памяти
"""
from __future__ import annotations

import argparse
import os
import pathlib
import sys
import tempfile
import time
from datetime import datetime

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

КОРЕНЬ = pathlib.Path(__file__).resolve().parent
# Кадры пишу в папку проекта. На рабочий стол программа писать не может:
# Windows отвечает Permission denied, это видно на скрине владельца.
# Копию на стол делает PowerShell командой copy, у него права есть.
# Папка кадров. Раньше была ekran рядом с ключами от хостингов, и туда же
# попадали снимки с банковской картой, которую владелец показывал.
# Теперь кадры идут в отдельную папку snimki, а ekran не трогаем.
ПАПКА = КОРЕНЬ / "snimki"
ЛОГ = ПАПКА / "snimki.log"

# Правило владельца: набралось ПОРОГ кадров, они не удаляются,
# а упаковываются в архив. Имя архива содержит время блока,
# чтобы по названию было видно, когда эти кадры сняты.
# Порог большой, чтобы у меня всегда был запас истории.
ПОРОГ = 10000
БЛОКОВ = 5000

ПАПКА.mkdir(parents=True, exist_ok=True)


def строка_лога(текст: str) -> None:
    """Дописать строку в лог и показать её в окне.

    Пишем в два места: в файл для меня и на печать для человека.
    Окно без вывода выглядит как зависшая программа, а это неправда.
    """
    метка = f"{datetime.now():%H:%M:%S}"
    строка = f"{метка}  {текст}"
    with ЛОГ.open("a", encoding="utf-8") as поток:
        поток.write(строка + "\n")
    print(строка, flush=True)


def все_кадры() -> list[pathlib.Path]:
    """Все файлы кадров, что бы формат ни был.

    Раньше тут стоял glob("*.png"), и съёмка с другим расширением была бы
    для архиватора невидимой: файлы копились бы вечно, потому что до
    порога архива они не доходили, а удаляться не должны были. Поэтому
    расширение спросим у самой папки, а не зашиваем в код.
    """
    кадры: list[pathlib.Path] = []
    for расширение in ("*.png", "*.jpg", "*.jpeg"):
        кадры.extend(ПАПКА.glob(расширение))
    return кадры


def убрать_старые() -> int:
    """Набралось порог, упаковываем кадры в архив с именем по времени.

    Порядок важен и он обратный обычному. Сначала архив, потом
    проверка архива, и только потом удаление оригиналов. Если архив
    получился плохим, оригиналы остаются на месте, потому что
    потерять два с половиной часа истории за один неудачный архив
    недопустимо.
    """
    import zipfile

    кадры = []
    for файл in все_кадры():
        try:
            кадры.append((файл.stat().st_mtime, файл))
        except OSError:
            continue

    if len(кадры) < ПОРОГ:
        return 0

    кадры.sort(key=lambda пара: пара[0])
    берём = кадры[:БЛОКОВ]
    if not берём:
        return 0

    начало = datetime.fromtimestamp(берём[0][0])
    конец = datetime.fromtimestamp(берём[-1][0])
    имя = (f"blok-{начало:%Y-%m-%d_%H-%M}"
           f"_po-{конец:%Y-%m-%d_%H-%M}.zip")

    папка_архивов = ПАПКА / "arhiv"
    папка_архивов.mkdir(parents=True, exist_ok=True)
    цель = папка_архивов / имя

    байт_до = sum(файл.stat().st_size for _, файл in берём)

    try:
        with zipfile.ZipFile(цель, "w", zipfile.ZIP_DEFLATED,
                             compresslevel=6) as архив:
            for _, файл in берём:
                архив.write(файл, файл.name)
    except Exception:                                             # noqa: BLE001
        return 0

    # ПРОВЕРКА: архив читается, в нём все файлы и ни один не битый
    try:
        with zipfile.ZipFile(цель, "r") as архив:
            список = архив.namelist()
            битый = архив.testzip()
    except Exception:                                             # noqa: BLE001
        return 0

    if битый is not None or len(список) != len(берём):
        строка_лога(f"архив {имя} плохой, оригиналы оставляю")
        return 0

    убрано = 0
    for _, файл in берём:
        try:
            файл.unlink()
            убрано += 1
        except OSError:
            continue

    строка_лога(f"архив {имя}: {убрано} кадров, было {байт_до} байт, "
                f"стало {цель.stat().st_size} байт")
    return убрано


РАСШИРЕНИЕ = {"png": ".png", "jpg": ".jpg"}


def снять_один(счётчик: int, настройки) -> bool:
    """Один кадр. Вернуть True, если получилось, иначе False."""
    try:
        from PIL import Image, ImageGrab
    except ImportError:
        строка_лога("СБОЙ нет библиотеки Pillow, "
                    "поставить: pip install pillow")
        return False

    расшир = РАСШИРЕНИЕ[настройки.format]

    # Имя кадра: дата, час, минута, секунда, микросекунды и счётчик.
    # Пример имени по требованию владельца: 20261014-1202-30-123456-000.png
    # Проверка на занятое имя обязательна. Без неё кадр, снятый в ту же
    # микросекунду после перезапуска, затёр бы предыдущий, а потеря
    # кадра выглядела бы как успех.
    # Проверка на занятое имя обязательна. Без неё кадр, снятый в ту же
    # миллисекунду после перезапуска, затёр бы предыдущий, а потеря
    # кадра выглядела бы как успех.
    имя = (f"{datetime.now():%Y%m%d-%H%M}-{datetime.now():%S}"
           f"-{datetime.now():%S}{счётчик:03d}" + расшир)
    # дата час минута секунда миллисекунды счётчик
    имя = (f"{datetime.now():%Y%m%d-%H%M}"
           f"-{datetime.now().microsecond // 1000000:02d}"
           f"-{datetime.now().microsecond % 1000000:06d}-{счётчик:03d}" + расшир)

    путь = ПАПКА / имя
    добавка = 0
    while путь.exists():
        добавка += 1
        путь = ПАПКА / f"{имя[:-len(расшир)]}-{добавка}{расшир}"

    try:
        кадр = ImageGrab.grab(all_screens=True)
    except Exception as ош:                                       # noqa: BLE001
        строка_лога(f"СБОЙ снимок не удался: {type(ош).__name__}: {ош}")
        return False

    if кадр is None:
        строка_лога("СБОЙ снимок вернул пустое значение")
        return False

    ширина, высота = кадр.size
    if ширина < 10 or высота < 10:
        строка_лога(f"СБОЙ кадр узкий {ширина} на {высота}")
        return False

    # Уменьшаем кадр ДО сохранения, а не после: JPEG жмёт уже готовую
    # картинку, и чем меньше в ней пикселей, тем меньше файл. Высота
    # считается от ширины, иначе кадр растянется или сплющится.
    исходный_размер = кадр.size
    if настройки.shirina and кадр.width > настройки.shirina:
        высота = round(кадр.height * настройки.shirina / кадр.width)
        кадр = кадр.resize((настройки.shirina, высота), Image.LANCZOS)

    try:
        if настройки.format == "jpg":
            # convert нужна: снимок экрана может прийти в RGBA, а JPEG
            # альфу не умеет и молча падает. optimize жмёт сильнее,
            # subsampling=1 — обычное для всех 4:2:0 без зерна на буквах.
            кадр.convert("RGB").save(путь, format="JPEG",
                                     quality=настройки.kachestvo,
                                     optimize=True, subsampling=1)
        else:
            кадр.save(путь, format="PNG")
    except Exception as ош:                                       # noqa: BLE001
        строка_лога(f"СБОЙ сохранить не вышло: {type(ош).__name__}: {ош}")
        return False

    # ПРОВЕРКА ЧТЕНИЕМ ОБРАТНО: сохранилось или только показалось
    if not путь.is_file():
        строка_лога("СБОЙ файла на диске нет")
        return False
    байт = путь.stat().st_size
    if байт < 1000:
        строка_лога(f"СБОЙ файл мал {байт} байт")
        return False
    try:
        проверка = Image.open(путь)
        размер = проверка.size
        формат_на_диске = проверка.format
        проверка.close()
    except Exception as ош:                                       # noqa: BLE001
        строка_лога(f"СБОЙ файл не читается: {type(ош).__name__}")
        return False

    # Проверка формата. Если попросили JPEG, а на диске PNG (или наоборот) —
    # это не мелочь: анализаторы ищут файлы по расширению, и незаметная
    # подмена формата оставила бы их смотреть в пустую папку.
    ожидаемый = "JPEG" if настройки.format == "jpg" else "PNG"
    if формат_на_диске != ожидаемый:
        строка_лога(f"СБОЙ формат не тот: просили {ожидаемый}, "
                    f"а на диске {формат_на_диске}")
        return False

    # Проверка размера. Снимок может прийти уже меньше заданного, если
    # окно на экране не full-screen. Это не поломка, но сообщить надо.
    if размер != tuple(кадр.size):
        строка_лога(f"ВНИМАНИЕ размер на диске {размер[0]}x{размер[1]}, "
                    f"а сохранял {кадр.size[0]}x{кадр.size[1]}")

    строка_лога(f"кадр {имя}  {размер[0]}x{размер[1]}  {байт} байт"
                + (f"  (с экрана {исходный_размер[0]}x{исходный_размер[1]})"
                   if tuple(исходный_размер) != tuple(кадр.size) else ""))
    return True


def главная() -> int:
    разбор = argparse.ArgumentParser(add_help=True)
    разбор.add_argument("--once", action="store_true")
    разбор.add_argument("--watch", action="store_true")
    # Пауза по умолчанию две секунды. Именно этим владелец просил
    # снимать реже. Ключ латиницей, потому что cmd и PowerShell
    # портят кириллицу в аргументах, а бат это уже проверял.
    разбор.add_argument("--sec", type=int, default=2)
    # Размер и качество кадра. Ключи латиницей по той же причине, что и
    # --sec: cmd и PowerShell портят кириллицу в аргументах.
    # Ширина None означает «пользователь не указывал», и тогда решение
    # принимает формат. Это важно: уменьшенный PNG тяжелее полного
    # (замерено: 1280x800 PNG — 432 КБ против 271 КБ у 1920x1200),
    # поэтому для PNG уменьшать нельзя, а для JPEG — нужно.
    разбор.add_argument("--shirina", type=int, default=None,
                        help="ширина кадра в точках, 0 — не уменьшать. "
                             "По умолчанию: JPEG 1280, PNG не уменьшать")
    разбор.add_argument("--kachestvo", type=int, default=75,
                        help="качество JPEG от 1 до 100, меньше — легче")
    # Папка для кадров. Раньше кадры падали в ekran рядом с ключами от
    # хостингов и в папку, которую владелец чистил из-за банковской карты.
    # Теперь папку можно задать, и по умолчанию она отдельная.
    разбор.add_argument("--papka", default="snimki", type=pathlib.Path,
                        help="куда складывать кадры. По умолчанию snimki")
    # Предел кадров в режиме watch. Раньше съёмка шла бесконечно и молча,
    # пока её не остановят: так в папку попадала банковская карта.
    # Теперь по умолчанию кадров 300, а снять больше можно явно.
    разбор.add_argument("--limit", type=int, default=300,
                        help="максимум кадров в режиме watch, 0 — без предела")
    # ФОРМАТ ПО УМОЛЧАНИЮ — PNG, И ЭТО СОЗНАТЕЛЬНО.
    # JPEG втрое легче, но почти все приборы студии ищут кадры как
    # Path(papka).glob("*.png") и после смены расширения молча видят
    # пустую папку: ошибки нет, программа отработала, результата нет.
    # Таких файлов 33, и они чужие. Пока они не переведены на оба
    # расширения, молчаливый отказ дороже экономии. Включается одним
    # ключом: --format jpg.
    разбор.add_argument("--format", choices=["jpg", "png"], default="png",
                        help="png — совместимо со всеми приборами (по умолчанию); "
                             "jpg — втрое легче, но приборы надо править")
    выбор = разбор.parse_args()

    if выбор.shirina is None:
        выбор.shirina = 1280 if выбор.format == "jpg" else 0
    elif выбор.shirina and выбор.shirina < 320:
        разбор.error("--shirina меньше 320: текст перестанет читаться")
    if not 1 <= выбор.kachestvo <= 100:
        разбор.error("--kachestvo должен быть от 1 до 100")
    if выбор.format == "png" and выбор.shirina:
        print("ВНИМАНИЕ: PNG при уменьшении тяжелее, чем в полный размер. "
              "Для экономии памяти нужен --format jpg")

    строка_лога(f"старт, папка {ПАПКА}")

    # Защита от второго запуска поверх первого. Две копии снимают в одну
    # папку одними и теми же именами и мешают друг другу: файл то есть,
    # то нет, и понять кто что делал невозможно. Второй запуск должен
    # сказать об этом прямо, а не молча работать вхолостую.
    if not выбор.once:
        замок = ПАПКА.parent / ".ekran.lock"
        мой_пид = str(os.getpid())
        if замок.is_file():
            чужой = замок.read_text(encoding="utf-8").strip()
            if чужой and чужой != мой_пид and _живой_процесс(чужой):
                строка_лога(f"ОТКАЗ: съёмка уже идёт, её ведёт процесс {чужой}")
                print(f"Съёмка уже идёт (процесс {чужой}). "
                      f"Второй раз запускать не нужно.")
                return 3
        try:
            замок.write_text(мой_пид, encoding="utf-8")
        except OSError:
            pass

    счётчик = 0
    try:
        return _работа(выбор, счётчик)
    finally:
        if not выбор.once:
            try:
                (ПАПКА.parent / ".ekran.lock").unlink(missing_ok=True)
            except OSError:
                pass


def _живой_процесс(пид: str) -> bool:
    """Жив ли процесс с таким номером."""
    try:
        import psutil  # noqa: F401
    except ImportError:
        psutil = None
    if psutil is not None:
        try:
            return psutil.pid_exists(int(пид))
        except Exception:                                            # noqa: BLE001
            return False
    try:
        os.kill(int(пид), 0)
        return True
    except (OSError, ValueError):
        return False


def _работа(выбор, счётчик: int) -> int:
    """Основной ход: один снимок или наблюдение."""
    # Папку задаём здесь, а не в разборе: ПАПКА и ЛОГ уже созданы
    # при импорте папкой по умолчанию, и молча переехали бы кадры
    # не туда, куда попросили.
    global ПАПКА, ЛОГ
    ПАПКА = pathlib.Path(выбор.papka)
    if not ПАПКА.is_absolute():
        ПАПКА = КОРЕНЬ / ПАПКА
    ЛОГ = ПАПКА / "snimki.log"
    ПАПКА.mkdir(parents=True, exist_ok=True)
    if выбор.once:
        снять_один(счётчик, выбор)
        убрать_старые()
        return 0

    if not выбор.watch:
        строка_лога("не указано ни одно действие, "
                    "запустить со --once или --watch")
        return 1

    строка_лога(f"режим watch, кадр каждые {выбор.sec} "
                f"{'секунду' if выбор.sec == 1 else 'секунды'}, "
                f"остановка Ctrl+C в этом окне")
    # Настройки кадра пишем в лог открытым текстом. Иначе по папке
    # нельзя понять, почему кадры стали мельче: а формат поменялся,
    # или окно на экране не во весь экран.
    строка_лога(f"кадр {выбор.shirina or 'на всю ширину экрана'} точек, "
                f"формат {выбор.format.upper()}"
                + (f", качество {выбор.kachestvo}" if выбор.format == "jpg" else ""))

    # Счётчики нужны, чтобы видеть правду: раньше вызов снятия не
    # проверялся, и при неудаче цикл молча продолжал работать. Со стороны
    # это выглядело так, будто программа «перестала снимать» и не пишет
    # ни об ошибке, ни слова. Теперь неудачи считаются и показываются.
    снято = 0
    не_снято = 0
    подряд_неудач = 0
    try:
        while True:
            счётчик += 1
            if снять_один(счётчик, выбор):
                снято += 1
                подряд_неудач = 0
            else:
                не_снято += 1
                подряд_неудач += 1
                строка_лога(f"ВНИМАНИЕ снимок не удался, "
                            f"неудач подряд: {подряд_неудач}")
                # Молчание здесь и было главной проблемой. Пять неудач
                # подряд — уже не случайность, а поломка. Останавливаемся,
                # чтобы не делать вид, что идёт съёмка.
                if подряд_неудач >= 5:
                    строка_лога("ОСТАНОВ: пять снимков подряд не получились")
                    return 2
            if выбор.limit and счётчик >= выбор.limit:
                строка_лога(f"достигнут предел {выбор.limit} кадров, "
                            f"съёмка остановлена сама")
                return 0
            if счётчик % 30 == 0:
                убрано = убрать_старые()
                всего = len(все_кадры())
                вес_папки = sum(
                    (файл.stat().st_size for файл in все_кадры()
                     if файл.is_file()),
                    0) / (1024 * 1024)
                строка_лога(f"кадров {счётчик}, снято {снято}, "
                            f"провалено {не_снято}, в папке {всего}, "
                            f"{вес_папки:.0f} МБ, "
                            f"убрано {убрано} при пороге {ПОРОГ}")
            time.sleep(max(0.2, выбор.sec))
    except KeyboardInterrupt:
        строка_лога(f"остановлено вручную на кадре {счётчик}")
        return 0


