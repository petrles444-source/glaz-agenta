#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
uhod — уборка папки кадров: архивирование и удаление старого.

ЗАЧЕМ. Съёмка идёт каждые две секунды. За месяц в папке `ekran`
набираются десятки тысяч кадров, и они просто занимают место. Раньше
с этим мог разобраться только человек вручную, то есть не
разбирался никто.

ЧТО ДЕЛАЕТ
  --pokaz      показать, сколько кадров и сколько они занимают
  --arhiv      сложить старые кадры в один zip и (по --snesti)
               удалить оригиналы, из архива они не вернутся
  --snesti     подтвердить удаление. Без этого ключа прибор только
               показывает план и ничего не делает
  --dney N     возраст в днях, старше которого кадр считается старым
  --zashchit N сколько самых свежих кадров не трогать никогда

ПОЧЕМУ ТАК МНОГО ПРЕДОСТОРОЖНОСТИ
  1. По умолчанию НИЧЕГО не удаляется. Сначала смотришь план, потом
     подтверждаешь. Ошибка в цифре не должна стоить кадров.
  2. Последние --zashchit кадров не трогаются вообще. Сейчас идёт
     съёмка — эти кадры ещё пишутся, и удаление на ходу обрезает файл.
  3. Оригинал удаляется только после того, как архив проверен: сверяем
     число файлов и сумму размеров. Не сошлось — не удаляем ничего.
  4. Трогаются только файлы с именем кадра (цифры, дефисы, .png/.jpg).
     Всё остальное в папке — не наше, и мы его не видим.
  5. Каждое действие пишется в журнал ekran/uhod.log: что и когда
     удалили. Если что-то пропало — ответ находится там.

ЗАПУСК
  python ekran/uhod.py --pokaz
  python ekran/uhod.py --arhiv --dney 7                    план
  python ekran/uhod.py --arhiv --dney 7 --snesti           выполнить
  python ekran/uhod.py --arhiv --dney 30 --zashchit 5000   свежее не трогаем
"""

from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import sys
import time
import zipfile
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

ПАПКА = Path(__file__).resolve().parent
ЖУРНАЛ = ПАПКА / "uhod.log"
АРХИВЫ = ПАПКА / "arhiv"

# Имя кадра: цифры и дефисы, иногда с '_' внутри. Именно так пишет
# съёмка. Всё, что под это не подходит, мы не трогаем: это может быть
# чужой файл, и удалять чужое без спроса нельзя.
ИМЯ_КАДРА = re.compile(r"^[\d][\d\-_]*\.(png|jpg|jpeg)$", re.IGNORECASE)


def кадры(папка: Path) -> list[Path]:
    """Только файлы кадров, отсортированные по времени записи."""
    найдено = [p for p in папка.iterdir()
               if p.is_file() and ИМЯ_КАДРА.match(p.name)]
    return sorted(найдено, key=lambda p: (p.stat().st_mtime, p.name))


def разобрать_дни(текст: str) -> int:
    """--dney 7d или --dney 7 — в днях."""
    t = текст.strip().lower().rstrip("дdдней")
    return max(0, int(t or 0))


def журнал(строка: str) -> None:
    ПАПКА.mkdir(parents=True, exist_ok=True)
    with ЖУРНАЛ.open("a", encoding="utf-8") as fh:
        fh.write(f"{time.strftime('%Y-%m-%d %H:%M:%S')}  {строка}\n")


def человеко_размер(байт: int) -> str:
    for единица in ("Б", "КБ", "МБ", "ГБ"):
        if байт < 1024 or единица == "ГБ":
            return f"{байт:.0f} {единица}" if единица == "Б" \
                else f"{байт:.1f} {единица}"
        байт /= 1024
    return f"{байт:.1f} ГБ"


def показать(все: list[Path]) -> None:
    всего = sum(p.stat().st_size for p in все)
    print(f"  папка кадров: {ПАПКА}")
    print(f"  кадров: {len(все)}")
    print(f"  занимают: {человеко_размер(всего)}")
    if все:
        старый = time.strftime("%d.%m.%Y %H:%M",
                              time.localtime(все[0].stat().st_mtime))
        новый = time.strftime("%d.%m.%Y %H:%M",
                              time.localtime(все[-1].stat().st_mtime))
        средний = всего / len(все)
        print(f"  от {старый}  до {новый}")
        print(f"  в среднем на кадр: {человеко_размер(средний)}")
        сутки = время_на_сутки(все)
        print(f"  за сутки набегает примерно: "
              f"{человеко_размер(сутки)}")
        print(f"  за месяц набежало бы: "
              f"{человеко_размер(сутки * 30)}")


def время_на_сутки(все: list[Path]) -> float:
    """Сколько байтов приходится на сутки, по окну между первым и
    последним кадром. Не по календарю, а по тому, что реально снято:
    камера могла стоять неделю, и тогда «в сутки» выходит огромным."""
    if len(все) < 2:
        return 0.0
    первый = все[0].stat().st_mtime
    последний = все[-1].stat().st_mtime
    сутки = (последний - первый) / 86400
    if сутки < 0.05:
        return 0.0
    байт = sum(p.stat().st_size for p in все)
    return байт / сутки


def выбрать_старые(все: list[Path], дни: int, защитить: int
                  ) -> tuple[list[Path], list[Path]]:
    """Делит кадры на «убираем» и «не трогаем».

    Порог по времени: старше N дней. Порог по свежести: последние
    --zashchit кадров не трогаем никогда, даже если они по времени
    старые (часы на машине могли быть сбиты).
    """
    отсечка = time.time() - дни * 86400
    свежие = set(все[-защитить:]) if защитить > 0 else set()
    старые, живые = [], []
    for p in все:
        if p in свежие or p.stat().st_mtime >= отсечка:
            живые.append(p)
        else:
            старые.append(p)
    return старые, живые


def собрать_архив(файлы: list[Path], дни: int, отметка: str) -> Path | None:
    """Кладёт файлы в zip. Возвращает путь архива или None."""
    АРХИВЫ.mkdir(parents=True, exist_ok=True)
    имя = f"kadry-do-{отметка}-dney{дни}.zip"
    путь = АРХИВЫ / имя
    # 8 вместо девяти: zip-файл не даёт дописать, и «дописать» здесь
    # означало бы положить в архив не всё.
    with zipfile.ZipFile(путь, "w", zipfile.ZIP_DEFLATED,
                         compresslevel=8) as z:
        for p in файлы:
            z.write(p, arcname=p.name)
    return путь


def проверить_архив(путь: Path, ждали: list[Path]) -> tuple[bool, str]:
    """Сверяет архив с оригиналами. Не сошлось — значит архив плохой.

    Считаем не только число файлов, но и сумму размеров: архив может
    содержать нужное число записей, но половина из них — пустые."""
    ждали_размер = sum(p.stat().st_size for p in ждали)
    with zipfile.ZipFile(путь, "r") as z:
        записи = z.infolist()
        их_размер = sum(и.file_size for и in записи)
        битый = z.testzip()
    if битый:
        return False, f"повреждён файл {битый}"
    if len(записи) != len(ждали):
        return False, (f"в архиве {len(записи)} файлов, "
                       f"а ждали {len(ждали)}")
    if их_размер != ждали_размер:
        return False, (f"размер не сошёлся: в архиве {их_размер}, "
                       f"на диске было {ждали_размер}")
    return True, "сходится"


def удалить(файлы: list[Path]) -> tuple[int, int]:
    """Удаляет файлы. Возвращает (сколько, сколько байт освободили)."""
    освободили = 0
    штук = 0
    for p in файлы:
        try:
            размер = p.stat().st_size
            p.unlink()
            освободили += размер
            штук += 1
        except OSError as ош:
            журнал(f"НЕ УДАЛИЛСЯ {p.name}: {ош}")
    return штук, освободили


def основная() -> int:
    ap = argparse.ArgumentParser(description="уборка папки кадров")
    ap.add_argument("--pokaz", action="store_true",
                    help="только показать, ничего не делая")
    ap.add_argument("--arhiv", action="store_true",
                    help="сложить старые кадры в архив")
    ap.add_argument("--snesti", action="store_true",
                    help="подтвердить удаление оригиналов после архива")
    ap.add_argument("--dney", default="7",
                    help="возраст в днях, старше которого кадр старый")
    ap.add_argument("--zashchit", type=int, default=200,
                    help="сколько самых свежих кадров не трогать")
    args = ap.parse_args()

    все = кадры(ПАПКА)

    if args.pokaz or not args.arhiv:
        показать(все)
        if not args.arhiv:
            return 0

    дни = разобрать_дни(args.dney)
    старые, живые = выбрать_старые(все, дни, args.zashchit)
    размер_старых = sum(p.stat().st_size for p in старые)

    print()
    print("=" * 68)
    print(f"  ПЛАН: старше {дни} дн.  (свежих не трогаю: "
          f"{args.zashchit})")
    print("=" * 68)
    print(f"  в архив пойдёт: {len(старые)} кадров, "
          f"{человеко_размер(размер_старых)}")
    print(f"  останется на диске: {len(живые)} кадров")

    if not старые:
        print("\n  Убирать нечего: все кадры свежие.")
        return 0

    if not args.snesti:
        print("\n  ЭТО ТОЛЬКО ПЛАН. Ничего не сделано.")
        print("  Повторите с --snesti, если всё верно.")
        return 0

    отметка = time.strftime("%Y%m%d-%H%M%S")
    print("\n  собираю архив...")
    путь = собрать_архив(старые, дни, отметка)
    if путь is None:
        print("  АРХИВ НЕ СОБРАН. Оригиналы не тронуты.")
        return 1

    размер_архива = путь.stat().st_size
    print(f"  архив: {путь.name}, "
          f"{человеко_размер(размер_архива)}")

    хорошо, причина = проверить_архив(путь, старые)
    if not хорошо:
        журнал(f"АРХИВ НЕ ПРОВЕРЕН {путь.name}: {причина}. "
               f"Оригиналы оставлены.")
        print(f"  АРХИВ НЕ ПРОВЕРЕН: {причина}")
        print("  Оригиналы оставлены, ничего не удалено.")
        return 1
    print("  архив проверен, содержимое сходится")

    штук, освободили = удалить(старые)
    журнал(f"Архив {путь.name}: {len(старые)} кадров, "
           f"{размер_старых} байт. Удалено {штук}, "
           f"освобождено {освободили} байт.")
    print(f"\n  удалено {штук} кадров, освобождено "
          f"{человеко_размер(освободили)}")
    print(f"  в архиве они лежат: {путь}")
    return 0


if __name__ == "__main__":
    raise SystemExit(основная())
